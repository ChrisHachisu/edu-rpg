#!/usr/bin/env python3
"""Track K report: reads /home/user/work/feel/out/<dungeon>-f<n>-<profile>.json (feel.cjs) and writes
REPORT.md + results.json (default /mnt/project-files/edu-rpg/autoloop/feel/), copying the failure
screenshots it cites into <dest>/shots/.

  python3 scripts/auto/feel/report.py [--out /home/user/work/feel/out] [--dest /mnt/project-files/edu-rpg/autoloop/feel]
"""
import argparse, glob, json, os, shutil, statistics as stx

ap = argparse.ArgumentParser()
ap.add_argument('--out', default='/home/user/work/feel/out')
ap.add_argument('--dest', default='/mnt/project-files/edu-rpg/autoloop/feel')
a = ap.parse_args()

PROF_ORDER = ['g1', 'g3', 'g6']
METHOD = '''
Generated by `scripts/auto/feel/report.py` from the per-floor JSON that `scripts/auto/feel/feel.cjs` writes. Game: the unmodified
build 98 at http://127.0.0.1:5500/ (/home/user/work/dist). Working-tree edits under `public/` (e.g. the M14 gust wisps) are NOT in what was played.

**How a trial runs.** A v4 save placed inside the dungeon on the floor (route cell 3) is continued from the title (the game's own
resume of a dungeon auto save). The child then walks the floor's learned route (plan `route`, from cell 3 to 3 cells short of
the stairs; Void Rift and Demon Castle: the stretch 5 cells before to 4 after the rift / mirror rooms) once per trial. Between
trials she is put back on the start with the engine's `ctx.place` (and `ctx.toFloor` after a drop), HP refilled, and the world runs
0.3-4.3 s at random so each attempt meets the beat at a different phase. Floors whose mechanic remembers a first visit (guards,
shadows, wires, spikes, the maze hunter) have their own floor flags cleared and the module re-loaded between trials, so every
trial there is a FIRST visit. Scaffolding moves are never used during a trial.

**The child.** Input: synthetic TouchEvents on the real `#dpad` element (index.html's handlers -> knob -> arrow keys +
`__DQ_STICK__`), the same path as a thumb, pushed to the rim. Time: game time (sum of Phaser frame deltas). Perception: each frame
the adapter records only what is drawn and inside the camera (lane glow/gust, stone glow/bolt, crust/cracks/molten, lit cells +
guard sprite, crystal light, wire glint / "Cut trip wire" pill, join glow strips, mirror badge, knight sprite); the child acts on
that snapshot as it was one reaction time ago (one draw per decision). Hidden timers and phases are never read for a decision.
Rule at a hazard: walk up to it; if it looks dangerous (or, for a hazard she knows is there, is not on screen yet) stop at
0.5-1.5 tiles (drawn per approach), releasing the stick `overshoot` ms late; wait until it looks safe; on a lane / bridge / shadow
zone keep going once on it; step back if the cell she waits on starts to look dangerous. Heading: aim at the next route cell
+ a smooth uniform error (re-drawn every 350 ms). Boxes are read for 1.5 s then tapped away. Battles are answered correctly.

| profile | reaction (sd) | heading error | release overshoot | re-plan after a failure |
|---|---|---|---|---|
| g1 (grade 1) | 700 ms (150) | +/-20 deg | 200 ms | 1.5 s |
| g3 (grade 3) | 500 ms (120) | +/-14 deg | 150 ms | 1.0 s |
| g6 (grade 6) | 350 ms (80) | +/-8 deg | 100 ms | 0.6 s |

**Pass / fail.** An attempt PASSES when she reaches the end of the route with no failure (Bandit Hideout: no ambush; spike
throw-backs are counted as mild hits and she walks round the sprung patch). An attempt ends at the first failure (blown off,
struck, caught on crust, caught by a guard / shadow / hunter / knight, fell into a pit, tripped a wire). "1st pass" = the
attempt number of the first clean pass. Failures are classified from her own state at the failure frame: release overshoot,
hit while waiting, hazard not on screen when she committed, turned bad within her reaction time, or turned during her crossing.

**Inputs (plans / nav).** The mech probes read plan JSON from `D2_PLANS` (default `/home/user/work/plans/out`, a scratch dir of an
earlier session that no longer exists) and `dungeon_authored.cjs` reads nav grids from `D2_NAV` (default `/home/user/work/e1/nav`).
The 108 floor plans (copied from the mount's `acts-integration/plans/`) now live in the repo at `scripts/auto/feel/data/plans/`
(about 1 MB); track X's `scripts/auto/explore/make_nav.py` rebuilds the nav grids from them plus the shipped walk masks and
cross-checks them against the shipped manifest (0 mismatches). From a clean checkout:
`export D2_PLANS=$PWD/scripts/auto/feel/data/plans; python3 scripts/auto/explore/make_nav.py --work /tmp/d2nav; export D2_NAV=/tmp/d2nav/nav`
then run any `scripts/acts/probe/mech/*.cjs` or `dungeon_authored.cjs` as before (verified: regenerated stormNest nav files are byte-identical).

**Fairness of the host.** 4 shared cores, several browsers: frame time per trial is recorded; a trial whose p95 frame time is
above 50 ms (under 20 fps) is marked coarse and left out of the rates when enough fair trials remain.
'''
SEVERE = ('blown off', 'caught', 'tripped')     # failures that end the attempt (a drop / a battle)


def cls1(ph, last):
    last = last or {}
    if ph == 'over':
        return 'release overshoot carried her onto it'
    if ph == 'wait':
        return 'hit while waiting (stood on / next to it)'
    if last.get('perceived') == 'unseen':
        return 'hazard not on screen when she committed'
    if last.get('perceived') in ('lull', 'calm', 'crust', 'dark', 'shine', 'hidden', None) and last.get('edgeState') not in (None, last.get('perceived')):
        return 'it turned bad within her reaction time (she saw it safe)'
    return 'went in while it looked safe; it turned during her crossing'


def causes_of(t):
    """why the child failed, from her own state at each failure frame"""
    out = [cls1(e.get('phase'), e) for e in (t.get('events') or [])]
    if t.get('kinds') and t.get('why') != 'arrived':
        ap_ = (t.get('approaches') or [])
        out.append(cls1(t.get('phase'), ap_[-1] if ap_ else {}))
    return out


def cls(t):
    c = causes_of(t)
    return c[0] if c else t.get('why')


def floor_summary(r):
    trials = [t for t in r['trials']]
    fair = [t for t in trials if not t.get('coarse')]
    use = fair if len(fair) >= max(5, len(trials) // 2) else trials
    n = len(use)
    passes = [t for t in use if t['ok']]
    first = next((i + 1 for i, t in enumerate(use) if t['ok']), None)
    kinds, why, causes = {}, {}, {}
    dmg, drops, back = [], 0, []
    for t in use:
        for k, v in (t.get('kinds') or {}).items():
            kinds[k] = kinds.get(k, 0) + v
        if not t['ok']:
            w = t['why'] if not t.get('kinds') else 'failure'
            why[w] = why.get(w, 0) + 1
        for c in causes_of(t):
            causes[c] = causes.get(c, 0) + 1
        p = t.get('penalty')
        if t.get('dmgPctTotal') is not None:
            dmg.append(t['dmgPctTotal'])
        elif p:
            dmg.append(p.get('dmgPct') or 0)
        if p:
            if p.get('droppedFloors'):
                drops += 1
            if p.get('cellsBack') is not None:
                back.append(p['cellsBack'])
    leads = [x['leadMs'] for t in use for x in (t.get('approaches') or []) if x.get('leadMs')]
    byunit = {}
    for t in use:
        for x in (t.get('approaches') or []):
            if x.get('leadMs') is not None and (x.get('seenDist') or 0) > 6 and (x.get('j') or 0) >= 5: byunit.setdefault(x['unit'], []).append(x['leadMs'])
    unitLead = {u: round(stx.median(v)) for u, v in byunit.items() if len(v) >= 3}
    fr = [t['frames'] for t in trials if t.get('frames', {}).get('n')]
    pt = [t['gameMs'] / 1000 for t in passes]
    stuck = [t for t in use if not t['ok'] and not t.get('kinds')]
    return {
        'dungeon': r['dungeon'], 'floor': r['floor'], 'mechanic': r['mechanic'], 'profile': r['profile']['key'],
        'trials': len(trials), 'fairTrials': len(fair), 'used': n, 'passes': len(passes), 'passRate': round(len(passes) / n, 3) if n else None,
        'firstPassAttempt': first, 'failuresByKind': kinds, 'failureCauses': causes, 'nonFailureEnds': why if stuck else {},
        'stuck': [{'t': t['t'], 'why': t['why'], 'shot': t.get('shot')} for t in stuck][:5],
        'timeToPassMedianS': round(stx.median(pt), 1) if pt else None, 'waitMedianS': round(stx.median([t['waitedMs'] / 1000 for t in passes]), 1) if passes else None,
        'failsPerAttempt': round(sum(kinds.values()) / n, 2) if n else None, 'completed': sum(1 for t in use if t.get('completed', t['ok'])), 'damagePctMean': round(sum(dmg) / len(dmg), 1) if dmg else 0, 'damagePctMax': max(dmg) if dmg else 0, 'drops': drops,
        'cellsBackMedian': stx.median(back) if back else None,
        'unitLeadMs': unitLead, 'cueLeadMsMedian': stx.median(leads) if leads else None, 'cueLeadMsMin': min(leads) if leads else None,
        'frameMeanMs': round(stx.mean([f['mean'] for f in fr]), 1) if fr else None, 'frameP95Ms': round(stx.mean([f['p95'] for f in fr]), 1) if fr else None,
        'coarseTrials': len(trials) - len(fair), 'inputPath': r.get('inputPath'), 'cue': r.get('cue'), 'notes': r.get('notes', []),
        'shots': sorted({t['shot'] for t in trials if t.get('shot')}),
        'failTrials': [{'t': t['t'], 'kinds': t.get('kinds'), 'cause': cls(t) if t.get('kinds') else t['why'], 'penalty': t.get('penalty'), 'shot': t.get('shot')} for t in use if not t['ok']][:6],
    }


files = sorted(glob.glob(os.path.join(a.out, '*-f*-g*.json')))
rows = []
for f in files:
    try:
        r = json.load(open(f))
    except Exception as e:
        print('skip', f, e)
        continue
    if r.get('entryFailed') or not r.get('trials'):
        rows.append({'dungeon': r['dungeon'], 'floor': r['floor'], 'mechanic': r['mechanic'], 'profile': r['profile']['key'], 'trials': 0, 'notes': r.get('notes', [])})
        continue
    rows.append(floor_summary(r))

# ---------------------------------------------------------------- flags
PROF = {'g1': 700, 'g3': 500, 'g6': 350}
flags = []
for s in rows:
    if not s.get('trials'):
        continue
    key = f"{s['dungeon']} f{s['floor']}"
    rep = f"node scripts/auto/feel/feel.cjs {s['dungeon']} {s['floor']} {s['profile']} 20"
    pr = s['passRate']
    if s['profile'] == 'g1' and pr is not None and (pr < 0.5 or (s['firstPassAttempt'] or 99) > 5):
        flags.append({'kind': 'too hard', 'floor': key, 'profile': s['profile'], 'score': 1 - pr, 'what': f"grade 1 passes {s['passes']}/{s['used']} ({pr:.0%}); first pass on attempt {s['firstPassAttempt']}; failures {s['failuresByKind']}; causes {s['failureCauses']}", 'repro': rep, 'shots': s['shots'][:2]})
    elif s['profile'] != 'g1' and pr is not None and pr < 0.5:
        flags.append({'kind': 'too hard', 'floor': key, 'profile': s['profile'], 'score': 0.8 * (1 - pr), 'what': f"{s['profile']} passes {s['passes']}/{s['used']} ({pr:.0%}); failures {s['failuresByKind']}; causes {s['failureCauses']}", 'repro': rep, 'shots': s['shots'][:2]})
    unf = {c: n for c, n in (s.get('failureCauses') or {}).items() if c in ('hazard not on screen when she committed', 'it turned bad within her reaction time (she saw it safe)')}
    if unf and sum(unf.values()) >= max(2, 0.2 * s['used']):
        flags.append({'kind': 'unfair (cue later than reaction)', 'floor': key, 'profile': s['profile'], 'score': sum(unf.values()) / s['used'], 'what': f"{sum(unf.values())}/{s['used']} attempts failed with no cue she could act on in time: {unf}; median cue lead {s['cueLeadMsMedian']} ms vs reaction {PROF[s['profile']]} ms", 'repro': rep, 'shots': s['shots'][:2]})
    late = {u: v for u, v in (s.get('unitLeadMs') or {}).items() if v < PROF[s['profile']] and s['mechanic'] in ('gust-walkways', 'crust-bridges', 'tripwires-and-spikes')}
    if late and s['profile'] == 'g1':
        flags.append({'kind': 'late cue (hazard comes on screen < reaction time before its edge)', 'floor': key, 'profile': s['profile'], 'score': 0.25, 'what': f"median ms between the hazard first showing on screen and her reaching her stopping point, per hazard: {late} (reaction {PROF[s['profile']]} ms at walking speed); the learned child copes by stopping blind, a first-time child walks in", 'repro': rep, 'shots': []})
    if s.get('stuck'):
        flags.append({'kind': 'stuck / possible soft-lock (check)', 'floor': key, 'profile': s['profile'], 'score': len(s['stuck']) / s['used'], 'what': f"{len(s['stuck'])} attempt(s) ended without a failure and without arriving: {s['nonFailureEnds']}", 'repro': rep, 'shots': [x['shot'] for x in s['stuck'] if x.get('shot')][:2]})
    if s['drops']:
        flags.append({'kind': 'penalty: drop a floor', 'floor': key, 'profile': s['profile'], 'score': 0.3 * s['drops'] / s['used'], 'what': f"{s['drops']}/{s['used']} attempts dropped her to the floor below (allowed by the rulings, but a long walk back)", 'repro': rep, 'shots': []})
    if s['damagePctMax'] and s['damagePctMax'] > 15:
        flags.append({'kind': 'penalty: large damage', 'floor': key, 'profile': s['profile'], 'score': s['damagePctMax'] / 100, 'what': f"up to {s['damagePctMax']}% HP lost in one attempt (mean {s['damagePctMean']}%), {s['failsPerAttempt']} hits per attempt", 'repro': rep, 'shots': []})

# trivial: every profile passes first try with no stop
by_floor = {}
for s in rows:
    if s.get('trials'):
        by_floor.setdefault((s['dungeon'], s['floor']), []).append(s)
for (d, f), ss in by_floor.items():
    if len(ss) >= 1 and all(x['passRate'] == 1.0 and (x['waitMedianS'] or 0) < 0.2 for x in ss):
        flags.append({'kind': 'no-op? (everyone passes, never waits)', 'floor': f'{d} f{f}', 'profile': ','.join(x['profile'] for x in ss), 'score': 0.05, 'what': 'all attempts of every profile run passed without waiting: the mechanic may not be doing anything on the learned route', 'repro': f'node scripts/auto/feel/feel.cjs {d} {f} g6 20', 'shots': []})
flags.sort(key=lambda x: -x['score'])

os.makedirs(os.path.join(a.dest, 'shots'), exist_ok=True)


def cp(p):
    if not p or not os.path.exists(p):
        return p
    dst = os.path.join(a.dest, 'shots', os.path.basename(p))
    if not os.path.exists(dst):
        shutil.copy(p, dst)
    return 'shots/' + os.path.basename(p)


for fl in flags:
    fl['shots'] = [cp(p) for p in fl['shots']]
for s in rows:
    for t in s.get('failTrials', []):
        t['shot'] = cp(t.get('shot'))
    s['shots'] = [cp(p) for p in s.get('shots', [])]

json.dump({'rows': rows, 'flags': flags}, open(os.path.join(a.dest, 'results.json'), 'w'), indent=1)

# ---------------------------------------------------------------- markdown
L = []
P = L.append
P('# Kid timing report (track K)\n')
P(METHOD.strip() + '\n')
# ---- static cue budget (from the plans): how long the visible warning lasts, against each profile's reaction time
PLANS = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data', 'plans')
def plan(d, f):
    try: return json.load(open(os.path.join(PLANS, f'{d}-f{f}.json')))
    except Exception: return None
CB = []
for d, key in (('stormNest', 'gust'), ('stormreachSpire', 'glow'), ('magmaTunnels', 'crust'), ('shadowCave', 'flicker')):
    for f in range(1, 8):
        p = plan(d, f)
        if not p: continue
        m = p['mechanic']['params']; tick = m.get('periodSec', 0) * 1000 / max(1, m.get('periodTicks') or 1)
        if key == 'gust': w, what = m['warnTicks'] * 185, f"window/walkway glow before the gust; gust {m['gustSec']} s, lull {m['lullSec']} s"
        elif key == 'glow': w, what = m['glowSec'] * 1000, f"stone glow before the bolt; a group strikes every {round(m['ticksBetweenGroups'] * tick / 1000, 2)} s"
        elif key == 'crust': w, what = m['warnTicks'] * tick, f"cracks glow before the crust melts; crust {m['crustSec']} s, molten {m['moltenSec']} s"
        else: w, what = 1000, f"crystals flicker before the light changes; shine {m['shineSec']} s, dim {m['dimSec']} s"
        CB.append((f'{d} f{f}', round(w), what))
CB.append(('banditHideout (all)', 370, '"Cut trip wire" pill + wire brightening start 2 tiles out = 0.37 s at full walking speed; otherwise a 0.52 s glint every 3.2 s'))
CB.append(('demonBarracks (all)', 0, 'a guard turning at the end of its beat throws its 6-tile cone at once (it first pauses 3 ticks = 0.55 s, the only tell)'))

P('## Pass rate per dungeon x profile (fair trials; passes / trials; floors)\n')
dungs = sorted({s['dungeon'] for s in rows})
P('| dungeon | mechanic | ' + ' | '.join(PROF_ORDER) + ' |')
P('|---|---|' + '---|' * len(PROF_ORDER))
for d in dungs:
    mech = next(s['mechanic'] for s in rows if s['dungeon'] == d)
    cells = []
    for p in PROF_ORDER:
        ss = [s for s in rows if s['dungeon'] == d and s['profile'] == p and s.get('trials')]
        if not ss:
            cells.append('-')
            continue
        n = sum(s['used'] for s in ss); k = sum(s['passes'] for s in ss)
        cells.append(f"{k}/{n} ({k / n:.0%}) f{','.join(str(s['floor']) for s in sorted(ss, key=lambda x: x['floor']))}")
    P(f'| {d} | {mech} | ' + ' | '.join(cells) + ' |')
P('\n## Cue budget (static, from the plans): warning length vs reaction time\n')
P('| floor | warning ms | g1 700 | g3 500 | g6 350 | what |')
P('|---|---|---|---|---|---|')
for k, w, what in CB:
    P(f"| {k} | {w} | {'%+d' % (w - 700)} | {'%+d' % (w - 500)} | {'%+d' % (w - 350)} | {what} |")
P('\nThe margin left after reacting must still cover stepping off / across (a 3-tile lane at 260 px/s is 0.55 s).')
P('\n## Ranked problems\n')
if not flags:
    P('(none yet)')
for i, fl in enumerate(flags[:25]):
    P(f"{i + 1}. **{fl['kind']}** - {fl['floor']} ({fl['profile']}): {fl['what']}  ")
    P(f"   repro: `NODE_PATH=/opt/node-tools/node_modules PROBE_URL=http://127.0.0.1:5500/ {fl['repro']}`" + (f"; shots: {', '.join(x for x in fl['shots'] if x)}" if fl['shots'] else ''))
P('\n## Per floor\n')
P('| floor | prof | trials (fair) | pass (clean) | reached end | 1st pass | failures per attempt | failures by kind | why she failed | time to pass (med s) | wait (med s) | dmg % mean/max | drops | cells back (med) | cue lead ms (med/min) | frame ms mean/p95 |')
P('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
for s in sorted(rows, key=lambda x: (x['dungeon'], x['floor'], PROF_ORDER.index(x['profile']) if x['profile'] in PROF_ORDER else 9)):
    if not s.get('trials'):
        P(f"| {s['dungeon']} f{s['floor']} | {s['profile']} | 0 | - | - | - | - | - | {'; '.join(s.get('notes', []))} | | | | | | | |")
        continue
    P(f"| {s['dungeon']} f{s['floor']} | {s['profile']} | {s['trials']} ({s['fairTrials']}) | {s['passes']}/{s['used']} | {s['completed']}/{s['used']} | {s['firstPassAttempt']} | {s['failsPerAttempt']} | {s['failuresByKind'] or '-'} | {s['failureCauses'] or (s['nonFailureEnds'] or '-')} | {s['timeToPassMedianS']} | {s['waitMedianS']} | {s['damagePctMean']}/{s['damagePctMax']} | {s['drops']} | {s['cellsBackMedian']} | {s['cueLeadMsMedian']}/{s['cueLeadMsMin']} | {s['frameMeanMs']}/{s['frameP95Ms']} |")
open(os.path.join(a.dest, 'REPORT.md'), 'w').write('\n'.join(L) + '\n')
print('wrote', os.path.join(a.dest, 'REPORT.md'), len(rows), 'rows', len(flags), 'flags')
