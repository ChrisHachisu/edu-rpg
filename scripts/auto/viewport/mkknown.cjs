'use strict';
// Rebuild scripts/auto/viewport/known-fails.json from capture runs (VP_OUT/m/*.json, see capture.cjs):
//   node scripts/auto/viewport/mkknown.cjs <m dir> [<second m dir> ...] [--write]
// Every measured failure is given the id of the first finding in findings.json whose match fits
// (rule, and optional regular expressions on sig / size / lang / screen). A failure no finding claims is
// printed and nothing is written: classify it first. With more than one run of the same size and language,
// a failure that is not in every run goes to "unstable" (the check accepts it failing or passing).
const fs = require('fs'), path = require('path');
const args = process.argv.slice(2), write = args.includes('--write'), dirs = args.filter(a => !a.startsWith('--'));
const F = JSON.parse(fs.readFileSync(path.join(__dirname, 'findings.json'), 'utf8'));
const V = require('./vplib.cjs');
const runs = {};   // key -> [run, ...]
for (const d of dirs) for (const f of fs.readdirSync(d).filter(f => /^[A-Za-z0-9]+-(en|ja-kana|ja-kanji)\.json$/.test(f))) { const r = JSON.parse(fs.readFileSync(path.join(d, f), 'utf8')); (runs[`${r.size}/${r.lang}`] = runs[`${r.size}/${r.lang}`] || []).push(r); }
const claim = (size, lang, screen, rule, sig) => { for (const f of F.findings) for (const m of f.match || []) { if (m.rule !== rule) continue; if (m.sig && !new RegExp(m.sig).test(sig)) continue; if (m.size && !new RegExp('^(' + m.size + ')$').test(size)) continue; if (m.lang && !new RegExp('^(' + m.lang + ')$').test(lang)) continue; if (m.screen && !new RegExp('^(' + m.screen + ')$').test(screen)) continue; return f.id; } return null; };
const out = { note: 'Generated by scripts/auto/viewport/mkknown.cjs from the capture runs of ' + (F.date || '') + ' (tree ' + (F.built || '') + '). Finding ids: autoloop/day4/viewport/REPORT.md.', built: F.built, date: F.date,
  findings: Object.fromEntries(F.findings.map(f => [f.id, `${f.rank} ${f.title}`])), fails: {}, unstable: {}, unreached: {} };
let orphans = 0, n = 0, nu = 0; const per = {};
for (const key of Object.keys(runs).sort()) {
  const [size, lang] = key.split('/'), rs = runs[key];
  for (const scr of V.SCREENS) {
    const sets = rs.map(r => r.screens[scr] ? new Set(r.screens[scr].issues.map(i => i.rule + '|' + i.sig)) : null);
    if (sets.every(s => !s)) { (out.unreached[key] = out.unreached[key] || []).push(scr); continue; }
    const all = new Set(); for (const s of sets) if (s) for (const k of s) all.add(k);
    for (const k of [...all].sort()) {
      const [rule, sig] = [k.slice(0, k.indexOf('|')), k.slice(k.indexOf('|') + 1)], id = claim(size, lang, scr, rule, sig);
      if (!id) { orphans++; console.log('UNCLAIMED', key, scr, k); continue; }
      const always = sets.every(s => s && s.has(k)), dst = always ? out.fails : out.unstable;
      ((dst[key] = dst[key] || {})[scr] = dst[key][scr] || {})[k] = id; if (always) n++; else nu++;
      (per[id] = per[id] || new Set()).add(key);
    }
  }
}
for (const f of F.findings) console.log(f.id, f.rank, (per[f.id] ? [...per[f.id]].join(' ') : '(no failure measured)').slice(0, 200));
console.log(`known ${n}, unstable ${nu}, unclaimed ${orphans}, unreached ${JSON.stringify(out.unreached)}`);
if (write && !orphans) { fs.writeFileSync(path.join(__dirname, 'known-fails.json'), JSON.stringify(out, null, 1)); console.log('wrote known-fails.json'); }
else if (write) console.log('not written: classify the unclaimed failures first');
