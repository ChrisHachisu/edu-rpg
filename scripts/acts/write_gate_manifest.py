#!/usr/bin/env python3
"""Pin every Acts 2-5 runtime file for the ship gate: runtime/manifests/acts-hifi-files.json.

    python3 scripts/acts/write_gate_manifest.py            # rewrite the pins from public/
    python3 scripts/acts/write_gate_manifest.py --check    # exit 1 if public/ and the pins differ

scripts/runtime_baseline.py verify-act1 is a CLOSED allowlist: a file in dist/ that it does not
name fails the gate as `extra`, and scripts/build-dist.sh copies into dist/ exactly the files the
gate reports as `missing`. So this manifest is both the allowlist and the copy list for:
  public/acts-hifi/**                 index, runtime script, minimap relief, towns table, overrides
  public/act{2,3,4,5}-hifi/**         chunks, plate, collision pack, underpaint, landmark sprites
  public/act1-hifi/town/**            only the towns listed in public/acts-hifi/towns.json
runtime_baseline.py loads it (ACTS_HIFI_FILES) and checks size, sha256 and the public/dist twin
of each entry. Re-run this after any change to those folders; it never touches dist/.
"""
import hashlib, json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'runtime/manifests/acts-hifi-files.json')
FOLDERS = ['acts-hifi', 'act2-hifi', 'act3-hifi', 'act4-hifi', 'act5-hifi']


def entry(rel):
    data = open(os.path.join(ROOT, 'public', rel), 'rb').read()
    return [len(data), hashlib.sha256(data).hexdigest()]


def collect():
    files = {}
    for folder in FOLDERS:
        base = os.path.join(ROOT, 'public', folder)
        for d, _, names in os.walk(base):
            for n in names:
                if n.startswith('.'): continue
                rel = os.path.relpath(os.path.join(d, n), os.path.join(ROOT, 'public')).replace(os.sep, '/')
                files[rel] = entry(rel)
    towns_p = os.path.join(ROOT, 'public/acts-hifi/towns.json')
    towns = json.load(open(towns_p))['towns'] if os.path.isfile(towns_p) else []
    town_dir = os.path.join(ROOT, 'public/act1-hifi/town')
    for tid in towns:
        for n in sorted(os.listdir(town_dir)) + ['npc/' + m for m in sorted(os.listdir(os.path.join(town_dir, 'npc')))]:
            if os.path.basename(n).startswith(tid + '-') and os.path.isfile(os.path.join(town_dir, n)):
                rel = 'act1-hifi/town/' + n
                files[rel] = entry(rel)
    return dict(sorted(files.items()))


def main():
    files = collect()
    doc = {'schema': 'qok-acts-hifi-gate-v1',
           'note': 'Generated by scripts/acts/write_gate_manifest.py. path -> [bytes, sha256].',
           'count': len(files), 'bytes': sum(v[0] for v in files.values()), 'files': files}
    if '--check' in sys.argv:
        have = json.load(open(OUT)) if os.path.isfile(OUT) else {}
        if have.get('files') != {k: list(v) for k, v in files.items()}:
            a, b = set(have.get('files', {})), set(files)
            changed = [k for k in a & b if have['files'][k] != files[k]]
            print(f'ACTS GATE MANIFEST STALE: +{len(b - a)} -{len(a - b)} changed {len(changed)} {sorted(changed)[:5]}')
            sys.exit(1)
        print(f'ACTS GATE MANIFEST OK: {len(files)} files, {doc["bytes"] / 1e6:.1f} MB')
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(doc, open(OUT, 'w'), indent=0)
    print(f'wrote {OUT}: {len(files)} files, {doc["bytes"] / 1e6:.1f} MB')


if __name__ == '__main__':
    main()
